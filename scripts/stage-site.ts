#!/usr/bin/env bun
// Copy the publishable part of site/ into a clean directory for GitHub Pages.
//
// site/ is both the web root and a source directory: it holds the view tests
// (lib.test.ts) beside the modules they test, and editors drop files there.
// Uploading site/ wholesale would publish whatever happens to be in it. This
// stages an explicit allow list instead and fails on anything it does not
// recognize, so a new public file is a deliberate edit here, not an accident.
//
//   bun run scripts/stage-site.ts [src=site] [dest=_site]
import { copyFileSync, existsSync, lstatSync, mkdirSync, readdirSync, rmSync } from "node:fs";
import { extname, join, resolve } from "node:path";

/** Top-level asset types the static site serves. No build step, so source is the asset. */
export const ASSET_EXTENSIONS = new Set([".html", ".js", ".css", ".svg"]);
/** Never published; skipped silently. Anything else unrecognized is an error. */
export const isExcluded = (name: string) => name.endsWith(".test.ts") || name === ".DS_Store";
/** Generated by `derive` in every mode. */
export const REQUIRED_DATA = ["summary.json", "orgs.json", "repos.json", "people.json", "org-people.json", "events.json", "governance.json"];
/** Written only by a full (GitHub overlay) build; the site hides those views when absent. */
export const OPTIONAL_DATA = ["items.json", "heartbeat.json"];
export const REQUIRED_ASSETS = ["index.html", "app.js"];

export type StageResult = { copied: string[]; skipped: string[] };

const regularFile = (path: string, rel: string) => {
  const st = lstatSync(path);
  if (!st.isFile()) throw new Error(`stage: ${rel} is not a regular file (symlinks and devices are refused)`);
};

export function stageSite(src: string, dest: string): StageResult {
  src = resolve(src);
  dest = resolve(dest);
  if (dest === src || dest.startsWith(src + "/") || src.startsWith(dest + "/")) {
    throw new Error(`stage: destination ${dest} must not overlap the source ${src}`);
  }
  const copied: string[] = [];
  const skipped: string[] = [];
  const plan: string[] = [];

  for (const name of readdirSync(src).sort()) {
    const path = join(src, name);
    if (isExcluded(name)) { skipped.push(name); continue; }
    if (name === "data") {
      if (!lstatSync(path).isDirectory()) throw new Error("stage: data is not a directory");
      for (const f of readdirSync(path).sort()) {
        if (isExcluded(f)) { skipped.push(`data/${f}`); continue; }
        if (!REQUIRED_DATA.includes(f) && !OPTIONAL_DATA.includes(f)) {
          throw new Error(`stage: unrecognized generated file data/${f}; add it to stage-site.ts if it is public`);
        }
        regularFile(join(path, f), `data/${f}`);
        plan.push(`data/${f}`);
      }
      continue;
    }
    if (name.startsWith(".") || !ASSET_EXTENSIONS.has(extname(name))) {
      throw new Error(`stage: unrecognized file ${name}; add its type to stage-site.ts if it is public`);
    }
    regularFile(path, name);
    plan.push(name);
  }

  const missing = [...REQUIRED_ASSETS, ...REQUIRED_DATA.map((f) => `data/${f}`)].filter((f) => !plan.includes(f));
  if (missing.length) throw new Error(`stage: missing ${missing.join(", ")}; run derive first`);

  // Validate everything before touching dest, so a refused stage leaves nothing half-written.
  rmSync(dest, { recursive: true, force: true });
  mkdirSync(join(dest, "data"), { recursive: true });
  for (const rel of plan) {
    copyFileSync(join(src, rel), join(dest, rel));
    copied.push(rel);
  }
  return { copied, skipped };
}

if (import.meta.main) {
  const [src = "site", dest = "_site"] = process.argv.slice(2);
  if (!existsSync(src)) {
    console.error(`stage: ${src} does not exist`);
    process.exit(1);
  }
  try {
    const { copied, skipped } = stageSite(src, dest);
    console.log(`staged ${copied.length} files into ${dest}${skipped.length ? `; skipped ${skipped.join(", ")}` : ""}`);
  } catch (e) {
    console.error((e as Error).message);
    process.exit(1);
  }
}
