import type {
  AvailableBranch, BranchCommit, BranchDest, BranchRecord, BranchUnavailableReason, Item, UnavailableBranch,
} from "./types.ts";

/**
 * Resolve the destination path from a `git log --numstat` row.
 *
 * Rename detection is left ON deliberately. With `--no-renames` a moved file is
 * reported as a whole-file delete plus a whole-file add: ucp#589, which moves
 * `retail_location.json` out of `shopping/`, measured 6,305 lines of work for
 * its author that way and 3,225 with renames detected. Nearly half the number
 * was file paths changing.
 *
 * The cost is this parse. Git compresses a rename into a common prefix and
 * suffix: `docs/specification/payment/{ => extensions}/actions/three-ds.md`
 * means `docs/specification/payment/actions/three-ds.md` became
 * `docs/specification/payment/extensions/actions/three-ds.md`. Without braces
 * the row is a plain `old => new`.
 */
export function destPath(raw: string): string {
  const arrow = raw.indexOf(" => ");
  if (arrow === -1) return raw;
  const open = raw.indexOf("{");
  const close = raw.indexOf("}", open + 1);
  if (open === -1 || close === -1 || open > arrow || close < arrow) return raw.slice(arrow + 4);
  return raw.slice(0, open) + raw.slice(arrow + 4, close) + raw.slice(close + 1);
}

/**
 * Machine-written files, excluded from every line count.
 *
 * Detection is by path. Reading content markers would be more precise, but the
 * marker sits in the file at HEAD while the lines being counted come from
 * arbitrary historical commits, so a content probe answers a question about the
 * wrong revision. Where a path is ambiguous the directory is named explicitly:
 * `src/ucp_sdk/models/schemas/` looks hand-written but all 228 files under it
 * carry `# generated by datamodel-codegen`.
 *
 * These files are excluded rather than shown separately because a person who
 * regenerates a schema has done one unit of work regardless of whether the
 * generator emitted 40 lines or 10,770 — and one contributor's ratio of
 * generated to hand-written here is 67:1.
 */
const GENERATED = [
  /(^|\/)(package-lock\.json|yarn\.lock|pnpm-lock\.yaml|npm-shrinkwrap\.json|uv\.lock|poetry\.lock|Cargo\.lock|Gemfile\.lock|go\.sum|composer\.lock)$/,
  /(^|\/)(dist|build|generated|__generated__|node_modules|vendor)\//,
  /(^|\/)src\/ucp_sdk\/models\/schemas\//,
  /(^|\/)spec_generated\.ts$/,
  /_pb2(_grpc)?\.pyi?$/,
  /\.min\.(js|css)$/,
  /\.(snap|lock)$/,
  /(^|\/)\.cspell/,
];

export const isGenerated = (path: string): boolean => GENERATED.some((re) => re.test(path));

export type Attribution = {
  email: string;
  added: number;
  deleted: number;
  commits: number;
  /** Files whose line counts could not be read, i.e. binary. Never counted as zero. */
  binary: number;
};

/**
 * Per-author line counts for one pull request's branch.
 *
 * Replays are dropped: a cherry-pick or rebase carries content already counted
 * where it first landed, and counting it again would credit the same lines to
 * two pull requests. Generated files are dropped. Binary files are counted as
 * files, never as lines, because numstat has no line count to give.
 *
 * Note what is NOT here: no blame, and no attempt to say whose lines survived.
 * Each person is measured over commits they themselves authored, so no later
 * edit can move a line from one person's column to another's. Reformatting a
 * colleague's paragraph adds to your own count and takes nothing from theirs.
 */
export function attribute(record: AvailableBranch): Attribution[] {
  const by = new Map<string, Attribution>();
  for (const commit of record.commits) {
    if (commit.replay) continue;
    const row = by.get(commit.email)
      ?? { email: commit.email, added: 0, deleted: 0, commits: 0, binary: 0 };
    row.commits++;
    for (const [added, deleted, path] of commit.files) {
      if (isGenerated(path)) continue;
      if (added === null || deleted === null) { row.binary++; continue; }
      row.added += added;
      row.deleted += deleted;
    }
    by.set(commit.email, row);
  }
  return [...by.values()].sort((a, b) => (b.added + b.deleted) - (a.added + a.deleted));
}

export const DESTS: readonly BranchDest[] = ["main", "component", "sidebranch", "unreachable"];
export const UNAVAILABLE_REASONS: readonly BranchUnavailableReason[] = ["no-merge-commit", "merge-commit-unfetchable"];
export const FULL_OID = /^[0-9a-f]{40}$/;

export const isAvailable = (r: BranchRecord): r is AvailableBranch => r.status === "available";

const branchKey = (r: { repo: string; number: number }) => `${r.repo}#${r.number}`;

/**
 * Every reason `records` is not exactly one well-formed branch record per landed
 * pull request in `items`, or [] when it is. Pure, so pull-branches can refuse to
 * write, derive can refuse to read, and verify can recount, all by one rule.
 *
 * The rule exists because absence used to be silent: a landed pull request whose
 * merge object was missing from the mirror produced no record, so ucp#223, #760
 * and #762 simply had no attribution and nothing said so. Coverage is now a
 * bijection, and every record that does not walk a branch says why.
 */
export function validateBranches(items: Record<string, Item>, records: readonly BranchRecord[]): string[] {
  const errors: string[] = [];
  const landed = new Map<string, Item>();
  for (const item of Object.values(items)) {
    if (item.kind !== "pr" || item.state !== "landed") continue;
    const key = branchKey(item);
    landed.set(key, item);
    // Abbreviated ids resolve only against objects already present, which is
    // exactly what a missing object is not. Raw files from before full ids
    // existed must be re-pulled, not guessed at.
    if (item.sha !== undefined && !FULL_OID.test(item.sha)) {
      errors.push(`${key}: merge oid ${JSON.stringify(item.sha)} is not a full 40-hex id — re-run pull:github`);
    }
  }

  const byKey = new Map<string, BranchRecord>();
  for (const r of records) {
    const key = branchKey(r);
    if (byKey.has(key)) { errors.push(`${key}: more than one branch record`); continue; }
    byKey.set(key, r);
    const item = landed.get(key);
    if (!item) { errors.push(`${key}: branch record for something that is not a landed pull request`); continue; }

    const status = (r as { status?: unknown }).status;
    if (status === "available") {
      const a = r as AvailableBranch;
      if (!item.sha) errors.push(`${key}: available record but the item names no merge commit`);
      else if (a.merge !== item.sha) errors.push(`${key}: walked merge ${String(a.merge)} but the item merged as ${item.sha}`);
      if (!DESTS.includes(a.dest)) errors.push(`${key}: unknown destination ${JSON.stringify(a.dest)}`);
      if (typeof a.base !== "string" || !FULL_OID.test(a.base)) errors.push(`${key}: base ${JSON.stringify(a.base)} is not a full id`);
      if (!Array.isArray(a.commits)) errors.push(`${key}: available record carries no commit list`);
      const viaOk = a.dest === "component" ? Number.isInteger(a.via)
        : a.dest === "sidebranch" ? typeof a.via === "string" && a.via.length > 0
        : a.via === null;
      if (!viaOk) errors.push(`${key}: ${a.dest} with via ${JSON.stringify(a.via)}`);
    } else if (status === "unavailable") {
      const u = r as UnavailableBranch;
      if (!UNAVAILABLE_REASONS.includes(u.reason)) errors.push(`${key}: unknown unavailability reason ${JSON.stringify(u.reason)}`);
      // The reason must be the TRUE one: "no merge commit" on an item that names
      // one would hide a fetch failure behind GitHub's data.
      const want = item.sha ? "merge-commit-unfetchable" : "no-merge-commit";
      if (UNAVAILABLE_REASONS.includes(u.reason) && u.reason !== want) {
        errors.push(`${key}: unavailable as ${u.reason}, but the item ${item.sha ? `names merge ${item.sha}` : "names no merge commit"}`);
      }
      if (u.merge !== (item.sha ?? null)) errors.push(`${key}: unavailable record names merge ${String(u.merge)}, item has ${item.sha ?? "none"}`);
      // An absence that carries lines is a measurement wearing an absence label.
      for (const f of ["dest", "via", "base", "commits"]) {
        if (f in u) errors.push(`${key}: unavailable record carries \`${f}\``);
      }
    } else {
      errors.push(`${key}: status ${JSON.stringify(status)} is neither available nor unavailable — re-run pull:branches`);
    }
  }

  // A component's carrier is, by construction, a delivery in the same repository.
  // Anything else means the carrier walk read the wrong range.
  for (const r of byKey.values()) {
    if (r.status !== "available" || r.dest !== "component") continue;
    const carrier = byKey.get(`${r.repo}#${String(r.via)}`);
    if (!carrier || carrier.status !== "available" || carrier.dest !== "main") {
      errors.push(`${branchKey(r)}: component of #${String(r.via)}, which is not a delivered pull request`);
    }
  }

  for (const key of landed.keys()) {
    if (!byKey.has(key)) errors.push(`${key}: landed pull request has no branch record`);
  }
  return errors;
}

export type { AvailableBranch, BranchCommit, BranchRecord, UnavailableBranch };
